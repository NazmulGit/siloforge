//! Stopword lists.

#[path = "stopwords_smart.rs"]
mod smart;

/// True when `w` (lowercase) is in the v1 keyword-extractor (SMART) stop list.
pub fn is_stopword(w: &str) -> bool {
    smart::SMART_STOPWORDS.binary_search(&w).is_ok()
}

