/// True when `w` (lowercase, straight apostrophes) ends a noun-phrase run.
pub fn is_phrase_breaker(w: &str) -> bool {
    PHRASE_BREAKERS.binary_search(&w).is_ok()
}

/// Adverb heuristic: `-ly` words with a typical adverbial suffix.
pub fn looks_adverb(w: &str) -> bool {
    w.len() > 5
        && [
            "ally", "ously", "ively", "fully", "lessly", "edly", "ingly", "ently", "antly", "ably",
            "ibly", "arly",
        ]
        .iter()
        .any(|s| w.ends_with(s))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_for_binary_search() {
        assert!(smart::SMART_STOPWORDS.windows(2).all(|w| w[0] < w[1]));
        assert!(
            PHRASE_BREAKERS.windows(2).all(|w| w[0] < w[1]),
            "PHRASE_BREAKERS not sorted"
        );
        assert!(is_stopword("the") && is_stopword("best") && !is_stopword("bike"));
        assert!(is_phrase_breaker("the") && !is_phrase_breaker("bike"));
        assert!(looks_adverb("carefully") && !looks_adverb("daily"));
    }
}
